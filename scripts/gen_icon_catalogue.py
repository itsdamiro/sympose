#!/usr/bin/env python3
"""Turn `scripts/icon_catalogue.txt` (Hugeicons names, one per concept) into the two files that list the icon set's
extra names: `ui/src/lib/icon-catalogue.ts` (name to icon, what the web app draws) and `sympose/icon_catalogue.py`
(the names, what the server accepts). A name is the Hugeicons name in kebab-case without its number (`Puzzle` is
`puzzle`, `MailLove01` is `mail-love`). One a hand-named icon in `persona-icons.ts` already has, by name or by icon,
is skipped. Run from the repo root; `--check` only reports whether the files are current."""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIST = ROOT / "scripts" / "icon_catalogue.txt"
PACKAGE = ROOT / "ui" / "node_modules" / "@hugeicons" / "core-free-icons" / "dist" / "esm"
HAND = ROOT / "ui" / "src" / "lib" / "persona-icons.ts"
TS_OUT = ROOT / "ui" / "src" / "lib" / "icon-catalogue.ts"
PY_OUT = ROOT / "sympose" / "icon_catalogue.py"


def kebab(stem: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "-", re.sub(r"\d+$", "", stem)).lower()


def hand_named() -> tuple[set[str], set[str]]:
    source = HAND.read_text(encoding="utf-8")
    block = source[source.index("const CURATED"):]
    block = block[: block.index("\n}\n")]
    pairs = re.findall(r'^\s+"?([a-z0-9-]+)"?:\s+(\w+),', block, re.M)
    return {n for n, _ in pairs}, {c for _, c in pairs}


def build() -> tuple[list[tuple[str, str]], str, str]:
    names, components = hand_named()
    stems = [s.strip() for s in LIST.read_text(encoding="utf-8").splitlines() if s.strip() and not s.startswith("#")]
    chosen: list[tuple[str, str]] = []
    seen = set(names)
    for stem in stems:
        component = stem + "Icon"
        if not (PACKAGE / f"{component}.js").exists():
            sys.exit(f"{stem}: no such icon in @hugeicons/core-free-icons")
        name = kebab(stem)
        if name in seen or component in components:
            continue
        seen.add(name)
        chosen.append((name, component))
    chosen.sort()
    imports = "\n".join(f"  {c}," for _, c in sorted({(c, c) for _, c in chosen}))
    rows = "\n".join(f'  "{n}": {c},' for n, c in chosen)
    ts = (
        "// Generated by scripts/gen_icon_catalogue.py from scripts/icon_catalogue.txt (docs/decisions/088); do not edit.\n"
        f"import {{\n{imports}\n}} from \"@hugeicons/core-free-icons\"\n"
        "import type { IconSvgElement } from \"@hugeicons/react\"\n\n"
        f"export const CATALOGUE: Record<string, IconSvgElement> = {{\n{rows}\n}}\n"
    )
    wrapped = "\n".join(
        "    " + ", ".join(f'"{n}"' for n, _ in chosen[i : i + 8]) + ","
        for i in range(0, len(chosen), 8)
    )
    py = (
        '"""The icon names the server accepts besides the hand-named ones in `look.py`. Generated by\n'
        "scripts/gen_icon_catalogue.py from scripts/icon_catalogue.txt (docs/decisions/088); do not edit.\"\"\"\n\n"
        f"NAMES = (\n{wrapped}\n)\n"
    )
    return chosen, ts, py


def main() -> None:
    chosen, ts, py = build()
    if "--check" in sys.argv:
        current = TS_OUT.exists() and TS_OUT.read_text() == ts and PY_OUT.exists() and PY_OUT.read_text() == py
        print("current" if current else "stale: run scripts/gen_icon_catalogue.py")
        sys.exit(0 if current else 1)
    TS_OUT.write_text(ts, encoding="utf-8")
    PY_OUT.write_text(py, encoding="utf-8")
    print(f"{len(chosen)} icons")


if __name__ == "__main__":
    main()
